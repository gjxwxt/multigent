// UpdateDeployRequestStatus performs a CAS status transition: the row is
// updated only when its current status equals `from`. Returns true when
// exactly one row transitioned.
func (db *SQLiteStore) UpdateDeployRequestStatus(workspaceID, id, from, to string) (ok bool, err error) {
	defer func() {
		if r := recover(); r != nil {
			err = fmt.Errorf("panic in UpdateDeployRequestStatus: %v", r)
		}
	}()
	workspaceID = strings.TrimSpace(workspaceID)
	id = strings.TrimSpace(id)
	if workspaceID == "" || id == "" || from == "" || to == "" {
		return false, fmt.Errorf("deploy request status transition requires workspace, id, from and to")
	}
	res, err := db.sql.Exec(`UPDATE deploy_requests SET status = ?
	WHERE workspace_id = ? AND id = ? AND status = ?`, to, workspaceID, id, from)
	if err != nil {
		return false, err
	}
	affected, err := res.RowsAffected()
	if err != nil {
		return false, err
	}
	return affected == 1, nil
}

