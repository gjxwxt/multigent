// HasApprovedDeployRequestForSHA reports whether the SHA already has a
// request in an approved-or-beyond state (approved/deploying/success) — used
// to fail closed against duplicate deployments of the same commit.
func (db *SQLiteStore) HasApprovedDeployRequestForSHA(workspaceID, projectID, sha string) (found bool, err error) {
	defer func() {
		if r := recover(); r != nil {
			err = fmt.Errorf("panic in HasApprovedDeployRequestForSHA: %v", r)
		}
	}()
	workspaceID = strings.TrimSpace(workspaceID)
	projectID = strings.TrimSpace(projectID)
	sha = strings.TrimSpace(sha)
	if workspaceID == "" || projectID == "" || sha == "" {
		return false, nil
	}
	var one int
	err = db.sql.QueryRow(`SELECT 1 FROM deploy_requests
	WHERE workspace_id = ? AND project_id = ? AND sha = ?
	  AND status IN ('approved','deploying','success') LIMIT 1`,
		workspaceID, projectID, sha).Scan(&one)
	if errors.Is(err, sql.ErrNoRows) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	return true, nil
}

